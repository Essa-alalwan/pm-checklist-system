function buildItems(
  templateItems: { id: string; label: string }[],
  overrides: Record<string, { status: ChecklistItemResult['status']; note?: string }> = {},
): ChecklistItemResult[] {
  return templateItems.map((item) => ({
    id: item.id,
    label: item.label,
    status: overrides[item.id]?.status ?? 'done',
    note: overrides[item.id]?.note,
  }))
}

function daysAgo(n: number): string {
  const d = new Date('2026-08-26T08:00:00')
  d.setDate(d.getDate() - n)
  return d.toISOString().slice(0, 10)
}

function makeBrushRows(holderCount: number, seedIndex: number): BrushLengthRow[] {
  const rows: BrushLengthRow[] = []
  for (let h = 1; h <= holderCount; h++) {
    for (const side of ['DE', 'NDE']) {
      rows.push({
        id: `brush-${h}-${side}`,
        holderNumber: h,
        side,
        lengthMm: Math.round((38 - (h + seedIndex) * 0.4) * 10) / 10,
      })
    }
  }
  return rows
}

